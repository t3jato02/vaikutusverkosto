// --- Projection: fit the outline's own bounding box into the SVG frame, with a
// cos(latitude) correction on longitude so Finland keeps its real proportions
// (tall and narrow) instead of looking stretched. Town dots use the same map.
const LATS = FINLAND_OUTLINE.map(([lat]) => lat);
const LONS = FINLAND_OUTLINE.map(([, lon]) => lon);
const GEO = {
  latMin: Math.min(...LATS),
  latMax: Math.max(...LATS),
  lonMin: Math.min(...LONS),
  lonMax: Math.max(...LONS),
};
const MID_LAT = (GEO.latMin + GEO.latMax) / 2;
const LON_COS = Math.cos((MID_LAT * Math.PI) / 180);

const FRAME = { w: 400, h: 500, padX: 20, padY: 40 };
const SPAN_X = (GEO.lonMax - GEO.lonMin) * LON_COS;
const SPAN_Y = GEO.latMax - GEO.latMin;
const SCALE = Math.min(FRAME.w / SPAN_X, FRAME.h / SPAN_Y);
const OFF_X = FRAME.padX + (FRAME.w - SPAN_X * SCALE) / 2;
const OFF_Y = FRAME.padY + (FRAME.h - SPAN_Y * SCALE) / 2;

function project(lat: number, lon: number): { x: number; y: number } {
  return {
    x: OFF_X + (lon - GEO.lonMin) * LON_COS * SCALE,
    y: OFF_Y + (GEO.latMax - lat) * SCALE,
  };
}

const OUTLINE_POINTS = FINLAND_OUTLINE.map(([lat, lon]) => {
  const { x, y } = project(lat, lon);
  return `${x.toFixed(1)},${y.toFixed(1)}`;
}).join(" ");

export default async function MapPage() {
  const byMunicipalityRaw = await db.entity.groupBy({
    by: ["municipality"],
    _count: { _all: true },
  });
  const byMunicipality = byMunicipalityRaw
    .map((r) => ({ municipality: r.municipality, count: (r._count as { _all: number })._all ?? 0 }))
    .filter((r) => r.municipality)
    .sort((a, b) => b.count - a.count);

  const rows = byMunicipality;
  const maxCount = Math.max(...rows.map((r) => r.count), 1);
  const plotted = rows.filter((r) => TOWNS[r.municipality!]);
  // Label only the busiest towns; the rest stay as dots (hover) + the list below,
  // so the dense southern cluster doesn't turn into overlapping text.
  const labelled = new Set(plotted.slice(0, 8).map((r) => r.municipality));

  return (
    <div className="space-y-8">
      <header>
        <h1 className="text-page-title">Kartta</h1>
        <p className="mt-1 max-w-3xl text-sm text-muted">
          Toimijoiden julkinen sijainti: kotikunta, vaalipiiri, virka tai institutionaalinen
          sijainti. Yksityisiä asuinpaikkoja ei koskaan päätellä tai näytetä.
        </p>
      </header>

      <section aria-label="Karttanäkymä" className="card overflow-x-auto">
        <svg
          viewBox="0 0 440 560"
          role="img"
          aria-label="Kaaviomainen kartta Suomesta: pisteet edustavat kuntia, joissa toimijoita on eniten"
          className="mx-auto w-full max-w-xl"
        >
          <rect x="10" y="10" width="420" height="540" rx="8" fill="#eef3f7" />
          <text x="220" y="30" textAnchor="middle" className="fill-ink-500" fontSize="11">
            Kaaviomainen kartta — pisteiden koko = toimijoiden määrä
          </text>

          {/* Finland silhouette */}
          <polygon
            points={OUTLINE_POINTS}
            fill="#e7ece2"
            stroke="#b7c2ab"
            strokeWidth="1"
            strokeLinejoin="round"
          />

          {plotted.map((r) => {
            const coords = TOWNS[r.municipality!];
            const { x, y } = project(coords[0], coords[1]);
            const rpx = 3.5 + (r.count / maxCount) * 13;
            return (
              <g key={r.municipality}>
                <circle cx={x} cy={y} r={rpx} fill="#0f5ea8" opacity="0.72" />
                {labelled.has(r.municipality) && (
                  <text x={x + rpx + 3} y={y + 3} className="fill-ink-600" fontSize="8">
                    {r.municipality}
                  </text>
                )}
                <title>{`${r.municipality}: ${r.count} toimijaa`}</title>
              </g>
            );
          })}
        </svg>
      </section>

      <section aria-label="Kunnat">
        <h2 className="section-title mb-2">Toimijat kunnittain</h2>
        <ul className="card divide-y divide-line">
          {rows.slice(0, 40).map((r) => (
            <li key={r.municipality} className="flex items-center justify-between gap-3 py-2">
              <span className="text-sm font-medium text-ink">{r.municipality}</span>
              <span className="text-sm tabular-nums text-muted">{formatNumber(r.count)}</span>
            </li>
          ))}
        </ul>
      </section>

      <p className="text-xs text-ink-400">
        Huomautus: näkymä on kaaviomainen. Alueellinen kokonaiskattavuus (kunnat, hyvinvointialueet,
        vaalipiirit) rakentuu vaiheessa B. Kuntien määrällinen näkymä päivittyy reaaliajasta.
      </p>
    </div>
  );
}
